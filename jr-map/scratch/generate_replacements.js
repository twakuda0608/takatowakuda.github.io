const content = fs.readFileSync('jr-map/data/official-kilos.js', 'utf8');
const lines = content.split('\n');

const plan = [];

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  const m = line.match(/^\s*"([^"]+)":\s*(\{.*\}),?$/);
  if (!m) continue;
  const lineId = m[1];
  if (!updates[lineId]) continue;

  const oldJsonStr = m[2];
  const obj = JSON.parse(oldJsonStr);
  const up = updates[lineId];
  const stMap = lineStMap[lineId] || {};

  for (const [name, km] of Object.entries(up)) {
    obj[name] = km;
    const stId = stMap[name];
    if (stId) {
      obj[stId] = km;
    }
  }

  // Preserve trailing comma if original line had it
  const hasComma = line.trim().endsWith(',');
  const newLine = `    "${lineId}": ${JSON.stringify(obj)}${hasComma ? ',' : ''}`;
  plan.push({
    lineNum: i + 1,
    lineId,
    oldLine: line,
    newLine
  });
}

console.log(`Prepared ${plan.length} line updates.`);
